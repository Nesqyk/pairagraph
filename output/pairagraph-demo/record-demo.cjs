const fs = require('node:fs');
const dir = 'output/pairagraph-demo';
fs.mkdirSync(`${dir}/frames`, {recursive:true});
(async()=>{
  const tabs = await (await fetch('http://127.0.0.1:9230/json/list')).json();
  const ws = new WebSocket(tabs.find(t=>t.type==='page').webSocketDebuggerUrl);
  await new Promise((r,j)=>{ws.onopen=r;ws.onerror=j});
  let id=0, frame=0; const pending=new Map(), captions=[], errors=[];
  ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.method==='Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text);if(pending.has(m.id)){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result)}};
  const call=(method,params={})=>new Promise((resolve,reject)=>{pending.set(++id,{resolve,reject});ws.send(JSON.stringify({id,method,params}))});
  const run=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result.value};
  const pause=ms=>new Promise(r=>setTimeout(r,ms));
  const wait=async expression=>{for(let i=0;i<150;i++){if(await run(expression))return;await pause(100)}throw new Error('Timeout: '+expression)};
  await call('Page.enable');await call('Runtime.enable');
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:810,deviceScaleFactor:1,mobile:false});
  await call('Page.addScriptToEvaluateOnNewDocument',{source:`document.addEventListener('DOMContentLoaded',()=>{const b=document.createElement('div');b.textContent='DEMO • simulated microphone and sample results';b.style.cssText='position:fixed;top:0;right:0;z-index:2000;background:#315744;color:white;font:11px Segoe UI;padding:5px 12px;border-bottom-left-radius:8px;pointer-events:none';document.body.appendChild(b)});`});
  const nav=async path=>{await call('Page.navigate',{url:'http://127.0.0.1:5002'+path});await wait(`document.readyState==='complete' && location.pathname===${JSON.stringify(path)}`)};
  const capture=async(seconds,caption)=>{const start=frame;for(let i=0;i<seconds*8;i++){const r=await call('Page.captureScreenshot',{format:'jpeg',quality:88,captureBeyondViewport:false});fs.writeFileSync(`${dir}/frames/${String(frame++).padStart(5,'0')}.jpg`,Buffer.from(r.data,'base64'));await pause(50)}captions.push({start:start/8,end:frame/8,text:caption});console.log(caption)};
  await nav('/student');
  await capture(5,'Pairagraph — a simple place to read, practice, and try again.');
  await run(`document.querySelector('.simple-hero form').requestSubmit()`);
  await wait(`!!document.querySelector('[data-start]')`);
  await capture(5,'Before reading, review the microphone prompt and give permission.');
  await run(`document.querySelector('[data-consent]').click()`);
  await capture(2,'Tick the consent box, then choose Record.');
  await run(`document.querySelector('[data-start]').click()`);
  await wait(`!!document.querySelector('.is-recording')`);
  await capture(6,'The story appears when recording starts. Read aloud at your own pace.');
  await run(`document.querySelector('[data-text-size]').click();window.scrollTo(0,200)`);
  await capture(4,'Make the text larger when needed. Stop stays at the bottom center.');
  await run(`document.querySelector('[data-stop]').click()`);
  await wait(`!!document.querySelector('.has-recording')`);
  await capture(6,'After Stop: choose peach Record again, or green See how I did.');
  await run(`document.querySelector('button[data-submit]').click()`);
  await wait(`!document.querySelector('[data-processing]').hidden`);
  await capture(3,'A spinning circle shows that your results are loading.');
  await wait(`location.pathname.includes('/analysis/')`);
  const readingId=await run(`location.pathname.split('/').pop()`);
  await capture(6,'Friendly feedback suggests a few practice words. The AI can mishear.');
  await run(`document.querySelector('.results-details').open=true;document.querySelector('.results-details').scrollIntoView({block:'start'})`);
  await capture(4,'Open Look at my reading to compare the story with what was heard.');
  await nav('/student/next/'+readingId);
  await capture(6,'One clear next step: Read this story. Or take a break.');
  await nav('/student/progress');
  await capture(5,'My progress keeps saved readings and suggested words together.');
  await nav('/student');
  await capture(4,'Pairagraph. Read. Practice. Try again.');
  const stamp=s=>{const ms=Math.round(s*1000);return `${String(Math.floor(ms/3600000)).padStart(2,'0')}:${String(Math.floor(ms/60000)%60).padStart(2,'0')}:${String(Math.floor(ms/1000)%60).padStart(2,'0')},${String(ms%1000).padStart(3,'0')}`};
  fs.writeFileSync(`${dir}/captions.srt`,captions.map((c,i)=>`${i+1}\n${stamp(c.start)} --> ${stamp(c.end)}\n${c.text}\n`).join('\n'));
  fs.writeFileSync(`${dir}/video-checks.json`,JSON.stringify({frames:frame,seconds:frame/8,browserErrors:errors,captions},null,2));
  await call('Browser.close');ws.close();if(errors.length)throw new Error(errors.join('; '));
})().catch(e=>{console.error(e);process.exit(1)});
